#!/usr/bin/env python3
"""Generate the SYNTHETIC demonstration community dataset and the repeatable SQL seed.

Run from the repo root:  python3 scripts/generate_seed.py
Outputs (deterministic, no randomness, safe to re-run):
  frontend/src/data/demo_community.json                       used by the local/offline similarity score
  supabase/migrations/20261101000003_seed_demo_data.sql       idempotent seed (ON CONFLICT DO NOTHING)

Dataset design (all fabricated, none of it comes from real people):
  120 synthetic profiles DEMO-0001..DEMO-0120. Every 6th profile has eligible_for_demo_calculation = false
  (a stand-in for "did not give consent to be counted"), leaving exactly 100 eligible profiles.
  For each topic k with target count n_k, eligible profile number e (0..99) reports that topic when
  (e * step_k + offset_k) mod 100 < n_k. Because step_k is coprime to 100 this selects exactly n_k of 100.
"""
import json, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA = ROOT / "frontend/src/data"
CATS = json.loads((DATA / "categories.json").read_text())
STORIES = json.loads((DATA / "demo_stories.json").read_text())

# slug: (target count out of 100 eligible profiles, step, offset)
RULES = {
    "acne": (65, 7, 3), "pigmentation": (48, 11, 5), "skin-tone": (41, 13, 8), "scars": (37, 17, 2),
    "dark-circles": (52, 19, 6), "social-media-pressure": (71, 21, 9), "appearance-insecurity": (78, 23, 4),
}
assert set(RULES) == {c["slug"] for c in CATS}, "RULES must cover every category"
TOTAL, INELIGIBLE_EVERY = 120, 6

profiles, e, j = [], 0, 0
for i in range(TOTAL):
    sid = f"DEMO-{i + 1:04d}"
    eligible = (i % INELIGIBLE_EVERY) != INELIGIBLE_EVERY - 1
    if eligible:
        cats = [s for s, (n, step, off) in RULES.items() if (e * step + off) % 100 < n]
        e += 1
    else:   # ineligible profiles still carry concerns, so the eligibility rule actually matters
        cats = [s for s, (n, step, off) in RULES.items() if (j * step + off) % 5 < 3]
        j += 1
    profiles.append({"id": sid, "eligible": eligible, "categories": cats})

doc = {
    "label": "Synthetic demonstration data for the Illuminate hackathon prototype. Not real people, not real statistics.",
    "version": 1,
    "profiles": profiles,
}
(DATA / "demo_community.json").write_text(json.dumps(doc, indent=1) + "\n")

q = lambda s: "'" + s.replace("'", "''") + "'"
out = ["-- GENERATED by scripts/generate_seed.py. Do not edit by hand. Safe to re-run: every insert is idempotent.",
       "-- All rows below are SYNTHETIC demonstration content (is_demo_content / is_demo_data = true).", "begin;", ""]
out.append("insert into public.story_categories (slug, name, description, sort_order) values")
out.append(",\n".join(f"  ({q(c['slug'])}, {q(c['name'])}, {q(c['description'])}, {c['sort_order']})" for c in CATS))
out.append("on conflict (slug) do nothing;\n")
for n, s in enumerate(STORIES):
    assert "$body$" not in s["body"]
    ts = f"timestamptz '2026-10-01 09:00:00+00' + interval '{n} days'"
    out.append(f"insert into public.stories (slug, author_id, title, content, status, is_anonymous, is_demo_content, created_at, updated_at, published_at)\n"
               f"values ({q(s['slug'])}, null, {q(s['title'])}, $body${s['body']}$body$, 'published', true, true, {ts}, {ts}, {ts})\non conflict (slug) do nothing;")
    cats = ", ".join(q(c) for c in s["cats"])
    out.append(f"insert into public.story_category_assignments (story_id, category_id)\n"
               f"select st.id, c.id from public.stories st join public.story_categories c on c.slug in ({cats})\n"
               f"where st.slug = {q(s['slug'])} and st.is_demo_content\non conflict do nothing;\n")
out.append("insert into public.demo_community_profiles (synthetic_id, is_demo_data, eligible_for_demo_calculation) values")
out.append(",\n".join(f"  ({q(p['id'])}, true, {'true' if p['eligible'] else 'false'})" for p in profiles))
out.append("on conflict (synthetic_id) do nothing;\n")
out.append("insert into public.demo_community_responses (demo_profile_id, category_id, is_demo_data)\nselect p.id, c.id, true\nfrom (values")
rows = [f"  ({q(p['id'])}, {q(c)})" for p in profiles for c in p["categories"]]
out.append(",\n".join(rows))
out.append(") as r(synthetic_id, slug)\njoin public.demo_community_profiles p on p.synthetic_id = r.synthetic_id\njoin public.story_categories c on c.slug = r.slug\non conflict (demo_profile_id, category_id) do nothing;\n")
out.append("commit;")
(ROOT / "supabase/migrations/20261101000003_seed_demo_data.sql").write_text("\n".join(out) + "\n")

elig = [p for p in profiles if p["eligible"]]
print(f"profiles={len(profiles)} eligible={len(elig)}")
for s in RULES: print(f"  {s}: {sum(s in p['categories'] for p in elig)}/{len(elig)}")
